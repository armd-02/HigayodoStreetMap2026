const assert = require('node:assert/strict');
const fs = require('node:fs');
const vm = require('node:vm');
const context = vm.createContext({ URL, console, Conf: { documentPreview: { use: true, field: 'custom_document' } }, document: { baseURI: 'https://example.org/map/', addEventListener() {} }, glot: { get: key => key } });
vm.runInContext(fs.readFileSync('lib/documentpreview.js', 'utf8') + '\nthis.preview = DocumentPreview;', context);
const preview = context.preview;
const input = { image: './guide.jpg', region: [0.1, 0.2, 0.3, 0.4] };
const raw = JSON.stringify(input);
assert.equal(preview.parse(raw).image, 'https://example.org/map/guide.jpg');
assert.equal(preview.parse('{broken'), null);
for (const image of ['javascript:alert(1)', 'data:image/svg+xml,x', 'file:///tmp/x', 'https://user:pass@example.org/image.jpg', '']) assert.equal(preview.parse({ ...input, image }), null);
for (const region of [[-1, 0, 1, 1], [0, 0, 0, 1], [0.9, 0, 0.2, 1], ['0', 0, 1, 1], [0, 0, Infinity, 1], [0, 0, 1]]) assert.equal(preview.parse({ ...input, region }), null);
assert.equal(JSON.stringify(preview.parse({ image: './guide.jpg' }).region), '[0,0,1,1]');
assert.equal(preview.collect([{ custom_document: raw }, { custom_document: raw }, { custom_document: '' }]).length, 1, 'deduplicate identical previews across facility posts');
assert.equal(preview.collect([{ document_preview: raw }]).length, 0, 'respect configured field name');
const html = preview.render([{ custom_document: raw }]);
assert.match(html, /data-document-preview=/);
assert.match(html, /width:333\.333/);
assert.match(html, /&quot;image&quot;/);
context.Conf.documentPreview.use = false;
assert.equal(preview.render([{ custom_document: raw }]), '');
context.Conf.documentPreview.use = true;
console.log('PASS: document preview parsing, configured field and deduplication');
