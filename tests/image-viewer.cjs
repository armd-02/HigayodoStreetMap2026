const assert = require('node:assert/strict');
const fs = require('node:fs');
const vm = require('node:vm');
const context = vm.createContext({ URL, console, document: { baseURI: 'https://example.org/map/' }, glot: { get: key => key } });
vm.runInContext(fs.readFileSync('lib/imageviewer.js', 'utf8') + '\nthis.viewer = ImageViewer;', context);
const viewer = context.viewer;
const input = { image: './guide.jpg', region: [0.1, 0.2, 0.3, 0.4] };
assert.equal(viewer.normalize({ image: './photo.jpg' }).region, undefined, 'ordinary photos have no selected area');
assert.equal(viewer.normalize({ image: 'blob:https://example.org/123' }).image, 'blob:https://example.org/123', 'cached Wikimedia images remain supported');
for (const image of ['javascript:alert(1)', 'data:text/html,x', 'https://user:pass@example.org/image.jpg']) assert.equal(viewer.normalize({ image }), null);
for (const region of [[-1,0,1,1], [0,0,0,1], [0,0,2,1], [0,0,NaN,1]]) assert.equal(viewer.normalize({ image:'./photo.jpg', region }), null);
viewer.viewer = { ready: true, stage: { clientWidth: 1000, clientHeight: 800 }, image: { naturalWidth: 2000, naturalHeight: 1000, style: {} }, value: input };
viewer.fit('region');
let view = viewer.viewer;
assert.ok(Math.abs((0.1 + 0.3 / 2) * 2000 * view.scale + view.x - 500) < 0.001, 'center selected region horizontally');
assert.ok(Math.abs((0.2 + 0.4 / 2) * 1000 * view.scale + view.y - 400) < 0.001, 'center selected region vertically');
const anchorBefore = (200 - view.x) / view.scale;
viewer.zoom(1.4, 200, 300);
assert.ok(Math.abs((200 - view.x) / view.scale - anchorBefore) < 0.001, 'zoom keeps image point under cursor');
viewer.fit('whole');
assert.equal(view.mode, 'whole');
viewer.fit('actual');
assert.equal(viewer.viewer.scale, 1, 'actual size is one image pixel per CSS pixel');
viewer.viewer.value = { image:'./photo.jpg' };
viewer.fit('whole');
assert.ok(viewer.viewer.scale < 1);
let opened, closed = 0, videosClosed = 0;
viewer.open = value => { opened = value; };
viewer.close = () => closed++;
vm.runInContext(fs.readFileSync('detail/activities.js', 'utf8') + '\nthis.activities = new Activities();', context);
context.activities.closeVideo = () => videosClosed++;
context.activities.viewImage({ getAttribute: () => 'https://example.org/full.jpg', currentSrc:'https://example.org/thumb.jpg', src:'https://example.org/thumb.jpg', alt:'Photo' });
assert.equal(opened.image, 'https://example.org/full.jpg', 'Wikimedia src_thumb still selects the larger image');
assert.equal(opened.region, undefined);
context.activities.viewImage({ getAttribute: () => '', currentSrc:'blob:https://example.org/123', src:'./fallback.jpg' });
assert.equal(opened.image, 'blob:https://example.org/123');
context.activities.closeMedia();
assert.equal(closed,1);
assert.equal(videosClosed,3);
console.log('PASS: shared viewer geometry, photo sources, actual size and media close integration');
